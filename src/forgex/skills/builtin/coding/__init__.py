"""Builtin coding skill for FORGEX."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from forgex.skills.base import Skill, SkillContext, SkillResult


class CodingSkill(Skill):
    """Builtin skill for code generation and editing tasks."""

    name = "coding"
    description = "Generate and edit code files within the workspace."
    version = "1.0.0"

    async def execute(self, context: SkillContext) -> SkillResult:
        try:
            workspace = Path(context.workspace)
            files_changed: list[str] = []
            output_parts: list[str] = []

            for rel in context.files:
                target = workspace / rel
                if not target.exists():
                    content = f"# {rel}\n# Generated by FORGEX coding skill\n\n# Task: {context.task}\n"
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_text(content, encoding="utf-8")
                    files_changed.append(rel)
                    output_parts.append(f"Created: {rel}")
                else:
                    output_parts.append(f"Exists (unchanged): {rel}")

            return SkillResult(
                success=True,
                output="\n".join(output_parts) or "No files to process.",
                data={"files_changed": files_changed},
                files_changed=files_changed,
            )
        except Exception as exc:
            return SkillResult(success=False, output="", error=str(exc))


__all__ = ["CodingSkill"]
