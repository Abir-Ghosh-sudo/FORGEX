"""Central resource management for FORGEX runtime."""

from __future__ import annotations

import asyncio
import logging
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from dataclasses import dataclass

from forgex.runtime.limits import (
    ResourceBudget,
    ResourceLimits,
    ResourceUsage,
)

logger = logging.getLogger(__name__)


@dataclass(frozen=True, slots=True)
class ResourceManagerStats:
    active_processes: int
    maximum_processes: int
    total_output_bytes: int
    maximum_output_bytes: int
    available_process_slots: int


class RuntimeResourceManager:
    """Coordinate process concurrency and resource accounting.

    All asynchronous process reservations must use process_slot().
    """

    def __init__(
        self,
        limits: ResourceLimits | None = None,
    ) -> None:
        self.limits = limits or ResourceLimits()

        self._budget = ResourceBudget(self.limits)
        self._semaphore = asyncio.Semaphore(self.limits.max_concurrent_processes)
        self._lock = asyncio.Lock()
        self._active_processes = 0
        self._total_output_bytes = 0
        self._closed = False

    @asynccontextmanager
    async def process_slot(self) -> AsyncIterator[None]:
        """Reserve a process slot for the duration of an operation."""

        if self._closed:
            raise RuntimeError("Resource manager is closed.")

        await self._semaphore.acquire()
        acquired = False

        try:
            async with self._lock:
                if self._closed:
                    raise RuntimeError("Resource manager is closed.")

                self._budget.acquire_process()
                self._active_processes += 1
                acquired = True

            yield

        finally:
            if acquired:
                async with self._lock:
                    self._budget.release_process()
                    self._active_processes -= 1

            self._semaphore.release()

    async def record_output(self, byte_count: int) -> None:
        """Account for output generated by runtime processes."""

        async with self._lock:
            if self._closed:
                raise RuntimeError("Resource manager is closed.")

            self._budget.record_output(byte_count)
            self._total_output_bytes += byte_count

    async def check_usage(self, usage: ResourceUsage) -> None:
        """Validate observed resource consumption."""

        async with self._lock:
            if self._closed:
                raise RuntimeError("Resource manager is closed.")

            self._budget.check_usage(usage)

    async def reset_output_accounting(self) -> None:
        """Reset aggregate output accounting."""

        async with self._lock:
            self._budget.reset_output()
            self._total_output_bytes = 0

    async def stats(self) -> ResourceManagerStats:
        """Return a consistent resource usage snapshot."""

        async with self._lock:
            return ResourceManagerStats(
                active_processes=self._active_processes,
                maximum_processes=self.limits.max_concurrent_processes,
                total_output_bytes=self._total_output_bytes,
                maximum_output_bytes=self.limits.max_output_bytes,
                available_process_slots=(
                    self.limits.max_concurrent_processes - self._active_processes
                ),
            )

    async def close(self) -> None:
        """Prevent new process reservations."""

        async with self._lock:
            self._closed = True

    @property
    def is_closed(self) -> bool:
        return self._closed
