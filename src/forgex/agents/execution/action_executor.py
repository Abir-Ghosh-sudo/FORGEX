"""Autonomous action executor for FORGEX agents.

Translates planned agent actions (file creation, modification, deletion,
and terminal execution) into real filesystem and environment changes.
"""

from __future__ import annotations

import asyncio
import difflib
import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


class ActionExecutionError(RuntimeError):
    """Raised when an agent action execution fails."""


@dataclass(slots=True)
class ActionExecutionResult:
    """Outcome of executing a single agent action."""

    action_type: str
    target: str
    success: bool
    diff: str = ""
    output: str = ""
    error: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "type": self.action_type,
            "target": self.target,
            "success": self.success,
            "diff": self.diff,
            "output": self.output,
            "error": self.error,
            "metadata": self.metadata,
        }


class ActionExecutor:
    """Executes structured actions generated by coding agents within a workspace."""

    def __init__(self, workspace: Path | None = None) -> None:
        self.workspace = Path(workspace).expanduser().resolve() if workspace else None

    def _resolve_target(self, workspace: Path, target_str: str) -> Path:
        """Safely resolve target path inside the workspace to prevent path traversal."""
        clean_target = target_str.strip().replace("\\", "/")
        if clean_target.startswith("/"):
            clean_target = clean_target.lstrip("/")

        target_path = (workspace / clean_target).resolve()
        try:
            target_path.relative_to(workspace.resolve())
        except ValueError as exc:
            raise ActionExecutionError(
                f"Security error: target path '{target_str}' escapes workspace boundary."
            ) from exc
        return target_path

    async def execute_action(
        self,
        workspace: Path,
        action: dict[str, Any],
    ) -> ActionExecutionResult:
        """Execute a single agent action against the workspace."""
        raw_type = str(
            action.get("type") or action.get("action") or "note"
        ).lower().strip()
        target_str = str(
            action.get("target") or action.get("file") or action.get("path") or ""
        ).strip()
        content = action.get("content") or action.get("text") or action.get("details")

        if raw_type in {"create", "write", "add"}:
            return await self._execute_write(workspace, target_str, content, overwrite=False)

        if raw_type in {"modify", "edit", "update", "patch"}:
            return await self._execute_write(workspace, target_str, content, overwrite=True)

        if raw_type in {"delete", "remove"}:
            return await self._execute_delete(workspace, target_str)

        if raw_type in {"command", "exec", "terminal", "run"}:
            command_str = target_str or str(action.get("command") or "").strip()
            return await self._execute_command(workspace, command_str)

        return ActionExecutionResult(
            action_type=raw_type,
            target=target_str,
            success=True,
            output="No-op or documentation action completed.",
        )

    async def _execute_write(
        self,
        workspace: Path,
        target_str: str,
        content: Any,
        *,
        overwrite: bool,
    ) -> ActionExecutionResult:
        if not target_str:
            return ActionExecutionResult(
                action_type="write",
                target="",
                success=False,
                error="No target file specified for write action.",
            )

        try:
            target_path = self._resolve_target(workspace, target_str)
            target_path.parent.mkdir(parents=True, exist_ok=True)

            text_content = str(content) if content is not None else ""
            old_text = ""
            if target_path.exists() and target_path.is_file():
                try:
                    old_text = target_path.read_text(encoding="utf-8", errors="replace")
                except Exception:
                    old_text = ""

            diff = ""
            if old_text:
                diff = "\n".join(
                    difflib.unified_diff(
                        old_text.splitlines(),
                        text_content.splitlines(),
                        fromfile=f"a/{target_str}",
                        tofile=f"b/{target_str}",
                        lineterm="",
                    )
                )

            target_path.write_text(text_content, encoding="utf-8")
            logger.info("Executed file write on %s (bytes=%d)", target_path, len(text_content))

            return ActionExecutionResult(
                action_type="modify" if overwrite and old_text else "create",
                target=target_str,
                success=True,
                diff=diff,
                output=f"Wrote {len(text_content)} bytes to {target_str}",
            )
        except Exception as exc:
            logger.exception("Failed executing write action on %s", target_str)
            return ActionExecutionResult(
                action_type="write",
                target=target_str,
                success=False,
                error=str(exc),
            )

    async def _execute_delete(self, workspace: Path, target_str: str) -> ActionExecutionResult:
        if not target_str:
            return ActionExecutionResult(
                action_type="delete",
                target="",
                success=False,
                error="No target file specified for delete action.",
            )

        try:
            target_path = self._resolve_target(workspace, target_str)
            if target_path.exists():
                if target_path.is_dir():
                    import shutil

                    shutil.rmtree(target_path)
                else:
                    target_path.unlink()
                logger.info("Deleted target %s", target_path)

            return ActionExecutionResult(
                action_type="delete",
                target=target_str,
                success=True,
                output=f"Deleted {target_str}",
            )
        except Exception as exc:
            logger.exception("Failed executing delete action on %s", target_str)
            return ActionExecutionResult(
                action_type="delete",
                target=target_str,
                success=False,
                error=str(exc),
            )

    async def _execute_command(
        self,
        workspace: Path,
        command_str: str,
        timeout_seconds: float = 60.0,
    ) -> ActionExecutionResult:
        if not command_str:
            return ActionExecutionResult(
                action_type="command",
                target="",
                success=False,
                error="No command specified.",
            )

        try:
            process = await asyncio.create_subprocess_shell(
                command_str,
                cwd=str(workspace),
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout_bytes, stderr_bytes = await asyncio.wait_for(
                process.communicate(),
                timeout=timeout_seconds,
            )
            stdout = stdout_bytes.decode(errors="replace")
            stderr = stderr_bytes.decode(errors="replace")
            exit_code = process.returncode or 0

            return ActionExecutionResult(
                action_type="command",
                target=command_str,
                success=(exit_code == 0),
                output=stdout,
                error=stderr if exit_code != 0 else None,
                metadata={"exit_code": exit_code},
            )
        except TimeoutError:
            return ActionExecutionResult(
                action_type="command",
                target=command_str,
                success=False,
                error=f"Command timed out after {timeout_seconds} seconds.",
            )
        except Exception as exc:
            return ActionExecutionResult(
                action_type="command",
                target=command_str,
                success=False,
                error=str(exc),
            )

    async def execute_actions(
        self,
        workspace: Path,
        actions: list[dict[str, Any]],
    ) -> dict[str, Any]:
        """Execute a list of actions and collect execution summary."""
        results: list[dict[str, Any]] = []
        files_changed: list[str] = []
        commands_run: list[str] = []
        errors: list[str] = []

        for action in actions:
            if not isinstance(action, dict):
                continue

            res = await self.execute_action(workspace, action)
            results.append(res.to_dict())

            if res.success:
                is_file_op = res.action_type in {"create", "modify", "delete", "write", "edit"}
                if is_file_op and res.target:
                    if res.target not in files_changed:
                        files_changed.append(res.target)
                elif res.action_type == "command" and res.target:
                    commands_run.append(res.target)
            else:
                if res.error:
                    errors.append(f"{res.action_type} on '{res.target}': {res.error}")

        return {
            "success": len(errors) == 0,
            "executed_count": len(results),
            "files_changed": files_changed,
            "commands_run": commands_run,
            "results": results,
            "errors": errors,
        }


__all__ = ["ActionExecutor", "ActionExecutionResult", "ActionExecutionError"]

